export function t(language: Language, key: string): string {
  return UI_TEXT[language][key] ?? UI_TEXT.en[key] ?? key;
}

export function statusLabel(language: Language, status: AuditStatus): string {
  return STATUS_LABELS[language][status];
}

export function severityLabel(language: Language, severity: Severity): string {
  return SEVERITY_LABELS[language][severity];
}

export function domainLabel(language: Language, value: string): string {
  return DOMAIN_LABELS[language][value] ?? value.replaceAll("_", " ");
}

export function controlTypeLabel(language: Language, value: string): string {
  return CONTROL_TYPE_LABELS[language][value] ?? domainLabel(language, value);
}

export function evidenceSourceLabel(language: Language, value: string): string {
  return EVIDENCE_SOURCE_LABELS[language][value] ?? domainLabel(language, value);
}

export function ruleCopy(language: Language, rule: GuidelineRule | { id: string; title: string; remediation?: string }): RuleCopy {
  if (language === "fr" && RULE_FR[rule.id]) return RULE_FR[rule.id];
  const fullRule = rule as GuidelineRule;
  return {
    title: rule.title,
    requirement: fullRule.requirement ?? rule.title,
    remediation: rule.remediation ?? "",
  };
}
